// Lazy loaders for the three on-device engines. Everything is served from this
// site (app/vendor, app/models), so nothing leaves the user's machine. OpenCV has
// a version-pinned CDN fallback for local/dev deployments where generated vendor
// assets have not been built yet; image data is never sent to that CDN.

const base = new URL('..', import.meta.url).href; // .../app/

let cvPromise;
export function loadOpenCV() {
  cvPromise ??= (async () => {
    const sources = [
      base + 'vendor/opencv/opencv.js',
      'https://cdn.jsdelivr.net/npm/@techstark/opencv-js@4.12.0-release.1/dist/opencv.js',
    ];
    let lastError;
    for (const src of sources) {
      try {
        await new Promise((resolve, reject) => {
          const script = document.createElement('script');
          script.src = src;
          script.async = true;
          script.onload = resolve;
          script.onerror = () => reject(new Error('Script request failed: ' + src));
          document.head.appendChild(script);
        });
        const cv = window.cv;
        if (!cv) throw new Error('OpenCV script loaded but window.cv was not initialized (' + src + ')');
        // The Emscripten module is a thenable that resolves to itself; awaiting it
        // (or resolving a promise with it) loops forever, so wait then drop then.
        if (typeof cv.then === 'function') await new Promise((resolve, reject) => {
          try { cv.then(() => resolve()); } catch (e) { reject(e); }
        });
        else if (!cv.Mat) await new Promise((resolve, reject) => {
          const previous = cv.onRuntimeInitialized;
          cv.onRuntimeInitialized = () => { previous?.(); resolve(); };
          cv.onAbort = (reason) => reject(new Error('OpenCV initialization aborted: ' + reason));
        });
        if (!cv.Mat) throw new Error('OpenCV initialized without its Mat API (' + src + ')');
        delete cv.then;
        return cv;
      } catch (error) {
        lastError = error;
        console.warn('OpenCV load attempt failed:', src, error);
      }
    }
    throw new Error('Could not load OpenCV.js from the app vendor path or the pinned CDN fallback. ' +
      'Check that app/vendor/opencv/opencv.js was generated by the project vendor build, and check network access. ' +
      'Last error: ' + (lastError?.message || lastError));
  })().catch((error) => {
    // Allow a later retry after a transient network/deployment failure.
    cvPromise = null;
    throw error;
  });
  return cvPromise;
}

let ocrPromise;
export function loadOCR(onProgress) {
  ocrPromise ??= (async () => {
    const { createWorker } = (await import(base + 'vendor/tesseract/tesseract.esm.min.js')).default;
    const worker = await createWorker('eng', 1, {
      workerPath: base + 'vendor/tesseract/worker.min.js',
      corePath: base + 'vendor/tesseract/core',
      langPath: base + 'vendor/tesseract/lang',
      gzip: true,
      logger: (m) => onProgress?.(m),
    });
    // PSM 11 = sparse text: diagram labels are scattered, not paragraphs.
    await worker.setParameters({ tessedit_pageseg_mode: '11', preserve_interword_spaces: '1' });
    return worker;
  })();
  return ocrPromise;
}

let samPromise;
export function loadSAM() {
  samPromise ??= (async () => {
    const T = await import(base + 'vendor/transformers/transformers.min.js');
    T.env.allowRemoteModels = false;
    T.env.allowLocalModels = true;
    T.env.localModelPath = base + 'models/';
    T.env.backends.onnx.wasm.wasmPaths = base + 'vendor/ort/';
    T.env.backends.onnx.wasm.proxy = true; // run inference in a worker so the page stays responsive
    // WASM everywhere: the WebGPU path is untested across judges' GPUs and the
    // CPU embed only costs a few seconds for this distilled model.
    const device = 'wasm';
    void hasWebGPU;
    const id = 'Xenova/slimsam-77-uniform';
    const model = await T.SamModel.from_pretrained(id, { dtype: 'fp32', device });
    const processor = await T.AutoProcessor.from_pretrained(id);
    return { T, model, processor, device };
  })();
  return samPromise;
}

async function hasWebGPU() {
  try {
    if (!navigator.gpu) return false;
    return !!(await navigator.gpu.requestAdapter());
  } catch { return false; }
}
