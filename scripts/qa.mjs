// Interaction QA: overlay mode, analysis tab, legend, merge/remove, tabs.
import { chromium } from 'playwright';
const base = process.env.BASE || 'http://localhost:5173';
const id = process.argv[2] || 'heart';
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1500, height: 1000 } });
p.on('pageerror', (e) => console.log('[pageerror]', e.message));
await p.goto(`${base}/?sample=${id}`);
await p.waitForFunction(() => /Done in/.test(document.querySelector('#status')?.textContent || ''), null, { timeout: 240000 });
console.log('labels', JSON.stringify(await p.$$eval('#labels input', (xs) => xs.map((x) => x.value))));
console.log('legend', JSON.stringify(await p.$$eval('#legend li', (xs) => xs.map((x) => x.innerText))));
await p.click('#viewmode button[data-mode="overlay"]'); await p.waitForTimeout(500);
await p.screenshot({ path: `eval-out/qa-${id}-overlay.png` });
await p.click('#viewmode button[data-mode="tactile"]');
await p.click('#tabs button[data-tab="analysis"]'); await p.waitForTimeout(500);
await p.locator('#labels li').nth(2).hover(); await p.waitForTimeout(300);
await p.screenshot({ path: `eval-out/qa-${id}-analysis.png` });
await p.click('#tabs button[data-tab="compare"]'); await p.waitForTimeout(500);
await p.screenshot({ path: `eval-out/qa-${id}-compare.png` });
await p.locator('.rail.right').evaluate((el) => el.scrollTo(0, 99999)); await p.waitForTimeout(200);
await p.screenshot({ path: `eval-out/qa-${id}-rail.png` });
await b.close();
